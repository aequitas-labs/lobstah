import { beforeEach, afterEach, it, expect } from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import type { Server } from 'node:http';
import type { AddressInfo } from 'node:net';
import { ensureLayout, readThread, takeHelm, startThread, postThread, triageThread, noteThread, sayThread, askDecision, readDecisionAnswer, listThreads, mirrorReadAllowed, mirrorWriteAllowed } from '@lobstah/core';
import { buildGlassSnapshot, serveGlass } from '../src/glass.js';
import { HELM_STOP_REMINDER } from '../src/charter.js';
import { removeTempDir } from '../../../test/temp-dir.js';
const cli = fileURLToPath(new URL('../dist/main.js', import.meta.url));
let home: string;
let server: Server | undefined;
beforeEach(() => {
  home = fs.mkdtempSync(path.join(os.tmpdir(), 'lobstah-thread-api-'));
  process.env.LOBSTAH_HOME = home; ensureLayout();
  fs.writeFileSync(path.join(home, 'config.toml'), `[repos.web]\npath = ${JSON.stringify(home.replace(/\\/g, '/'))}\ntrunk = "main"\n[limits]\nattachmentMaxBytes = 64\n`);
});
afterEach(async () => { if (server) await new Promise<void>(resolve => server!.close(() => resolve())); server = undefined; delete process.env.LOBSTAH_HOME; removeTempDir(home); });
function run(...args: string[]) {
  const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => !k.startsWith('CLAUDE') && !k.startsWith('CODEX') && k !== 'LOBSTAH_GROUNDS'));
  return spawnSync(process.execPath, [cli, ...args], { cwd: home, env: { ...env, LOBSTAH_HOME: home }, encoding: 'utf8', timeout: 15_000 });
}
it('delivers a thread event and supports triage, notes, card answers, chat rounds and resolution through the CLI', () => {
  const item = startThread({ grounds: 'home', text: 'Where does Helm go?' });
  const wake = run('man', 'wait', '--timeout', '0');
  expect(wake.status, wake.stderr).toBe(0);
  expect(wake.stdout).toContain('event: thread'); expect(wake.stdout).toContain('kind: untriaged'); expect(wake.stdout).toContain(item.text);
  takeHelm({ sessionId: 'test-helm', grounds: { name: 'home', repos: ['web'] }, ttlMs: 60_000 });
  const invoke = (...args: string[]) => { const r = run('man', ...args, '--session', 'test-helm'); expect(r.status, r.stderr + r.stdout + JSON.stringify(args)).toBe(0); return r; };
  invoke('triage', item.id, '--as', 'thread');
  invoke('note', item.id, '--decided', 'Keep Reviews', '--open', 'Choose navigation');
  const ask = invoke('ask', '--thread', item.id, '--title', 'Use the middle tab?', '--option', 'Yes');
  const key = /^key: (decision:[a-f0-9]{8})$/m.exec(ask.stdout)![1]!;
  expect(run('man', 'answer', key, '--option', 'Yes').status).toBe(0);
  const answer = run('man', 'wait', '--timeout', '0', '--session', 'test-helm');
  expect(answer.stdout).toContain('event: decision-answer'); expect(answer.stdout).toContain(`thread: ${item.id}`);
  invoke('discuss', item.id, '--said', 'Chris and helm settled navigation in chat');
  invoke('resolve', item.id, '--outcome', 'answered', '--note', 'Helm gets the middle tab');
  const view = run('man', 'threads', item.id);
  expect(JSON.parse(view.stdout)).toMatchObject({ state: 'resolved', kind: 'thread', cards: [{ answer: { option: 'Yes' } }] });
  expect(readThread(item.id)?.rounds.at(-1)?.entries[0]).toMatchObject({ via: 'chat' });
  expect(HELM_STOP_REMINDER).toBe('If this reply requires human action, put it on a card.');
});
it('lets the helm write in the conversation with man say, with attachments, and wakes it on the reply', () => {
  const item = startThread({ grounds: 'home', text: 'Is the deck too busy?' });
  takeHelm({ sessionId: 'test-helm', grounds: { name: 'home', repos: ['web'] }, ttlMs: 60_000 });
  const shot = path.join(home, 'deck.png');
  fs.writeFileSync(shot, Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 0]));
  const said = run('man', 'say', item.id, 'A', 'little:', 'see', 'the', 'sketch', '--attach', shot, '--session', 'test-helm');
  expect(said.status, said.stderr).toBe(0);
  expect(JSON.parse(said.stdout)).toMatchObject({ unreadResponse: true, responseText: 'A little: see the sketch' });
  expect(readThread(item.id)?.rounds[0]?.entries.at(-1)).toMatchObject({ by: 'helm', text: 'A little: see the sketch', attachments: [{ name: 'deck.png' }] });
  expect(buildGlassSnapshot().threads?.[0]).toMatchObject({ unreadResponse: true, waitingForHelm: false });
  expect(run('man', 'say', item.id, '--session', 'test-helm').status).toBe(2);
  expect(run('man', 'say', item.id, 'Not the helm').status).not.toBe(0);
  postThread(item.id, { text: 'Show me the other one' });
  const wake = run('man', 'wait', '--timeout', '0', '--session', 'test-helm');
  expect(wake.stdout).toContain('event: thread'); expect(wake.stdout).toContain('Show me the other one'); expect(wake.stdout).not.toContain('see the sketch');
});
it('tracks a resolved thread through its todo and lets man wait close it when the todo is done', () => {
  const item = startThread({ grounds: 'home', text: 'Check the deck test tomorrow' });
  takeHelm({ sessionId: 'test-helm', grounds: { name: 'home', repos: ['web'] }, ttlMs: 60_000 });
  const invoke = (...args: string[]) => { const r = run(...args, '--session', 'test-helm'); expect(r.status, r.stderr + r.stdout + JSON.stringify(args)).toBe(0); return r; };
  expect(run('todo', 'add', 'Nothing to tie', '--thread', 'abcdef01-1234-4000-8000-abcdef012345', '--session', 'test-helm').status).toBe(2);
  const added = invoke('todo', 'add', 'Check the deck test', '--thread', item.id);
  expect(added.stdout).toContain(`thread: ${item.id}`);
  const todoId = /^todo: (\d+)$/m.exec(added.stdout)![1]!;
  const resolved = JSON.parse(invoke('man', 'resolve', item.id, '--outcome', 'answered', '--note', 'Checking tomorrow').stdout);
  expect(resolved).toMatchObject({ state: 'tracking', tracked: [{ kind: 'todo', ref: todoId, state: 'open' }] });
  expect(buildGlassSnapshot().threads?.[0]).toMatchObject({ state: 'tracking', waitingForHelm: false });
  run('man', 'wait', '--timeout', '1', '--session', 'test-helm');
  expect(readThread(item.id)?.state).toBe('tracking');
  invoke('todo', 'done', todoId);
  run('man', 'wait', '--timeout', '1', '--session', 'test-helm');
  expect(readThread(item.id)?.state).toBe('resolved');
  expect(readThread(item.id)?.rounds.at(-1)?.entries.at(-1)).toMatchObject({ event: 'tracked', text: 'Todo Check the deck test finished' });
});
it('authorizes writes, validates uploads, serves rounds on demand, and keeps snapshots small', async () => {
  server = serveGlass(0); await new Promise<void>(resolve => server!.once('listening', resolve));
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  const token = ((await (await fetch(`${base}/data`)).json()) as { focusToken: string }).focusToken;
  const send = (kind: string, payload: unknown, supplied = token, origin = base) => fetch(`${base}/requests`, { method: 'POST', headers: { Origin: origin, 'content-type': 'application/json', 'x-lobstah-token': supplied }, body: JSON.stringify({ kind, payload }) });
  expect((await send('thread-start', { text: 'Hello' }, 'wrong')).status).toBe(403);
  expect((await send('thread-start', { text: 'Hello' }, token, 'https://evil.test')).status).toBe(403);
  expect((await send('thread-start', { text: '' })).status).toBe(400);
  expect((await send('thread-start', { text: 'Bad', files: [{ name: '../file.png', data: 'YQ==' }] })).status).toBe(400);
  expect(listThreads()).toEqual([]);
  const png = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 0]);
  const response = await send('thread-start', { text: 'Consider the navigation', kind: 'bait', files: [{ name: 'phone.png', data: png.toString('base64') }] });
  expect(response.status).toBe(201);
  const { item } = await response.json() as { item: { id: string; kind: string } };
  expect(item.kind).toBe('untriaged');
  expect((await send('thread-post', { id: item.id, text: 'Keep Reviews' })).status).toBe(201);
  const view = await (await fetch(`${base}/threads/${item.id}`)).json();
  expect(view).toMatchObject({ rounds: [{ entries: [{ text: 'Consider the navigation' }] }, { entries: [{ text: 'Keep Reviews' }] }] });
  expect(Buffer.from(await (await fetch(`${base}/threads/${item.id}/files/phone.png`)).arrayBuffer())).toEqual(png);
  expect((await fetch(`${base}/threads/${item.id}/files/..%2Fphone.png`)).status).toBe(404);
  const summary = buildGlassSnapshot().threads![0]!;
  expect(summary.roundCount).toBe(2); expect(summary).not.toHaveProperty('rounds'); expect(summary).not.toHaveProperty('attachments');
  expect(mirrorReadAllowed(`/threads/${item.id}`)).toBe(true);
  expect(mirrorReadAllowed(`/threads/${item.id}/files/phone.png`)).toBe(true);
  expect(mirrorReadAllowed(`/threads/${item.id}/files/..%2Fsecret`)).toBe(false);
  expect(mirrorWriteAllowed('thread-post')).toBe(true);
});

it('shares response read cursors and subscriber notices across the local and mirror HTTP paths', async () => {
  const item = startThread({grounds:'home',text:'Navigation'}); triageThread(item.id,'thread');
  const {meta} = askDecision({title:'Use Helm?',thread:item.id,askedBy:'helm',maxBytes:100});
  const shown = readThread(item.id)!.responseSeq!;
  noteThread(item.id,{decided:['Keep Reviews']});
  expect(readThread(item.id)!.responseSeq).toBe(shown);
  sayThread(item.id,{text:'Reviews stays'});
  server = serveGlass(0); await new Promise<void>(r => server!.once('listening',r));
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  const token = ((await (await fetch(`${base}/data`)).json()) as {focusToken:string}).focusToken;
  const send = (kind:string, through:number) => fetch(`${base}/requests`,{method:'POST',headers:{Origin:base,'content-type':'application/json','x-lobstah-token':token,'x-lobstah-relay':'wharf'},body:JSON.stringify({kind,payload:{id:item.id,through}})});
  expect((await send('thread-seen',shown)).status).toBe(200);
  expect(await (await fetch(`${base}/threads/${item.id}`)).json()).toMatchObject({seenThrough:shown,responseSeq:shown+1,unreadResponse:true});
  const notices = await (await fetch(`${base}/thread-notices`)).json();
  expect(notices).toMatchObject([{thread:item.id,seq:shown+1}]);
  expect((await send('thread-notice-dismiss',shown+1)).status).toBe(200);
  expect(await (await fetch(`${base}/thread-notices`)).json()).toEqual([]);
  expect(readDecisionAnswer(meta.key)).toBeUndefined();
  expect(mirrorReadAllowed('/thread-notices')).toBe(true);
  expect(mirrorWriteAllowed('thread-seen')).toBe(true);
});
