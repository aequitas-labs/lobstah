// The hosted glass uses the same CSS and safe Markdown elements as local glass.
import * as esbuild from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export async function buildWharfGlass() {
  const js = await esbuild.build({ entryPoints: [resolve(root, 'services/wharf/glass/src/main.ts')], bundle: true,
    format: 'iife', platform: 'browser', target: 'es2020', minify: true, write: false, legalComments: 'none' });
  const styles = ['apps/cli/glass/glass.css', 'services/wharf/glass/glass.css'].map((p) => readFileSync(resolve(root, p), 'utf8').replace(/\r\n/g, '\n')).join('\n');
  const css = await esbuild.transform(styles, { loader: 'css', minifyWhitespace: true, legalComments: 'none' });
  const script = js.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  const style = css.code.replace(/<\/style/gi, '<\\/style');
  const output = '// GENERATED by scripts/build-wharf-glass.mjs — do not edit.\n'
    + `export const GLASS_SCRIPT: string = ${JSON.stringify(script)};\nexport const GLASS_CSS: string = ${JSON.stringify(style)};\n`;
  writeFileSync(resolve(root, 'services/wharf/src/glass-page.generated.ts'), output);
  return { script, style };
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildWharfGlass();
